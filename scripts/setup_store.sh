#!/usr/bin/env bash
# Idempotent prep for Q1 Store web + Isaac Lab 3 tutorial + Hermes.
#
#   bash scripts/setup_store.sh              # install/check everything, write .data/store.env
#   bash scripts/setup_store.sh --check      # report only (exit 1 if something missing)
#   bash scripts/setup_store.sh --hermes-only
#   bash scripts/setup_store.sh --isaaclab-only
#   bash scripts/setup_store.sh --with-isaacsim   # also uv sync --extra isaacsim (large)
#
# Then:  bash scripts/start_store.sh --port 8878 --with-hermes
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
DATA="${Q1_STORE_DATA:-$ROOT/.data}"
ENV_FILE="${Q1_STORE_ENV_FILE:-$DATA/store.env}"
VENV="${Q1_HERMES_VENV:-$ROOT/.venv-llm}"
MODEL_DIR="$DATA/models/NousResearch--Hermes-3-Llama-3.1-8B-GGUF"
MODEL_FILE="$MODEL_DIR/Hermes-3-Llama-3.1-8B.Q4_K_M.gguf"
MODEL_REPO="NousResearch/Hermes-3-Llama-3.1-8B-GGUF"
MODEL_NAME="Hermes-3-Llama-3.1-8B.Q4_K_M.gguf"
CUDART_PARENT="$DATA/llama-cpp/cudart"
CUDART_DIR="$CUDART_PARENT/cudart-llama-b12018-bin-ubuntu-cuda-12.8-x64"
CUDART_URL="https://github.com/ggml-org/llama.cpp/releases/download/b12018/cudart-llama-b12018-bin-ubuntu-cuda-12.8-x64.tar.gz"
LLAMA_INDEX="https://abetlen.github.io/llama-cpp-python/whl/cu124"
ISAAC_DEFAULT="${Q1_ISAACLAB3_ROOT:-$HOME/IsaacLab3}"
ISAAC_TAG="${Q1_ISAACLAB3_TAG:-v3.0.0}"
ISAAC_REPO="${Q1_ISAACLAB3_REPO:-https://github.com/isaac-sim/IsaacLab.git}"
PY="${Q1_SETUP_PYTHON:-}"
HF_CLI="$(command -v hf || command -v huggingface-cli || true)"
UV_BIN="$(command -v uv || true)"

CHECK_ONLY=0
HERMES_ONLY=0
ISAAC_ONLY=0
WITH_ISAACSIM=0
for arg in "$@"; do
  case "$arg" in
    --check) CHECK_ONLY=1 ;;
    --hermes-only) HERMES_ONLY=1 ;;
    --isaaclab-only) ISAAC_ONLY=1 ;;
    --with-isaacsim) WITH_ISAACSIM=1 ;;
    -h|--help)
      sed -n '2,14p' "$0"
      exit 0
      ;;
    *)
      echo "unknown option: $arg" >&2
      exit 2
      ;;
  esac
done

mkdir -p "$DATA" "$MODEL_DIR" "$CUDART_PARENT" "$DATA/llama-cpp"

log()  { printf '+ %s\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
skip() { printf '  · skip %s\n' "$*"; }
need() { printf '  ! need %s\n' "$*"; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

pick_python() {
  if [[ -n "$PY" ]]; then
    command -v "$PY" >/dev/null || die "Q1_SETUP_PYTHON=$PY not found"
    return
  fi
  if command -v python3.11 >/dev/null; then
    PY=python3.11
  elif command -v python3 >/dev/null && python3 -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 11) else 1)'; then
    PY=python3
  else
    die "need Python 3.11+ (python3.11 recommended)"
  fi
}

is_isaaclab3() {
  local root="$1"
  [[ -f "$root/pyproject.toml" ]] || return 1
  # v3 markers: tagged 3.x checkout, launch_simulation API, or pyproject version.
  if [[ -d "$root/.git" ]]; then
    local desc
    desc="$(git -C "$root" describe --tags --exact-match 2>/dev/null \
      || git -C "$root" describe --tags --always 2>/dev/null \
      || true)"
    [[ "$desc" =~ ^v?3\. ]] && return 0
  fi
  if grep -Rql --include='*.py' 'def launch_simulation' \
      "$root/source" "$root/scripts" "$root/isaaclab" 2>/dev/null; then
    return 0
  fi
  grep -Eiq '^\s*version\s*=\s*"3\.' "$root/pyproject.toml" 2>/dev/null && return 0
  return 1
}

hermes_import_ok() {
  [[ -x "$VENV/bin/python" ]] || return 1
  local cudart="$CUDART_DIR"
  local nv="${Q1_NVIDIA_LIBS:-$HOME/.venv/myisaacsim/lib/python3.11/site-packages/nvidia}"
  LD_LIBRARY_PATH="$cudart:${nv}/cuda_runtime/lib:${nv}/cublas/lib:${nv}/cuda_nvrtc/lib:${LD_LIBRARY_PATH:-}" \
    "$VENV/bin/python" -c 'import llama_cpp, fastapi, uvicorn' 2>/dev/null
}

write_env() {
  local isaac_root="${1:-}"
  local hermes_model="${2:-}"
  cat >"$ENV_FILE" <<EOF
# Generated by scripts/setup_store.sh — sourced by scripts/start_store.sh
# $(date -Iseconds)
Q1_STORE_ROOT=$ROOT
Q1_STORE_DATA=$DATA
Q1_STORE_PYTHON=${Q1_STORE_PYTHON:-$PY}
Q1_HERMES_VENV=$VENV
Q1_HERMES_MODEL=$hermes_model
Q1_CUDART_DIR=$CUDART_DIR
Q1_LLM_PORT=${Q1_LLM_PORT:-8877}
Q1_LLM_BASE_URL=http://127.0.0.1:\${Q1_LLM_PORT:-8877}/v1
Q1_LLAMA_SERVER=$ROOT/scripts/hermes_server.sh
EOF
  if [[ -n "$isaac_root" ]]; then
    printf 'Q1_ISAACLAB3_ROOT=%s\n' "$isaac_root" >>"$ENV_FILE"
  fi
  if [[ -n "$hermes_model" && -f "$hermes_model" ]]; then
    printf 'Q1_LLM_MODEL=%s\n' "$hermes_model" >>"$ENV_FILE"
  fi
  ok "wrote $ENV_FILE"
}

# ---------------------------------------------------------------------------
pick_python
log "Q1 Store setup  root=$ROOT  python=$PY  check_only=$CHECK_ONLY"

MISSING=0

# ---- tools ----
if [[ "$ISAAC_ONLY" -eq 0 ]]; then
  log "tools"
  if command -v "$PY" >/dev/null; then ok "python: $($PY -V 2>&1)"; else need "python 3.11+"; MISSING=1; fi
  if [[ -n "$UV_BIN" ]]; then ok "uv: $UV_BIN"; else need "uv (https://docs.astral.sh/uv/)"; MISSING=1; fi
  if [[ -n "$HF_CLI" ]]; then ok "hf cli: $HF_CLI"; else need "hf CLI (pip install -U huggingface_hub)"; MISSING=1; fi
fi

# ---- Hermes ----
setup_hermes() {
  log "Hermes (llama-cpp + GGUF)"
  if [[ "$CHECK_ONLY" -eq 1 ]]; then
    if hermes_import_ok; then ok "llama-cpp-python in $VENV"; else need "llama-cpp-python[server] in $VENV"; MISSING=1; fi
    if [[ -f "$CUDART_DIR/libcudart.so.12" ]]; then ok "cudart: $CUDART_DIR"; else need "cudart libs under $CUDART_PARENT"; MISSING=1; fi
    if [[ -f "$MODEL_FILE" ]]; then ok "model: $(du -h "$MODEL_FILE" | awk '{print $1}') $MODEL_FILE"; else need "model $MODEL_FILE"; MISSING=1; fi
    return
  fi

  if [[ ! -x "$VENV/bin/python" ]]; then
    log "creating $VENV"
    "$PY" -m venv "$VENV"
  else
    skip "venv exists $VENV"
  fi

  if hermes_import_ok; then
    skip "llama-cpp-python already importable"
  else
    log "installing llama-cpp-python[server] (CUDA wheel index)"
    "$VENV/bin/pip" install -U pip wheel setuptools >/dev/null
    "$VENV/bin/pip" install 'llama-cpp-python[server]' --extra-index-url "$LLAMA_INDEX"
    hermes_import_ok || die "llama-cpp-python install finished but import still fails (check CUDA libs)"
    ok "llama-cpp-python installed"
  fi

  if [[ -f "$CUDART_DIR/libcudart.so.12" ]]; then
    skip "cudart already at $CUDART_DIR"
  else
    log "downloading CUDA runtime libs"
    local tar="$DATA/llama-cpp/cudart-12.8.tar.gz"
    if [[ ! -f "$tar" ]]; then
      curl -fL --retry 3 -o "$tar" "$CUDART_URL"
    else
      skip "cudart archive already downloaded"
    fi
    mkdir -p "$CUDART_PARENT"
    tar -xzf "$tar" -C "$CUDART_PARENT"
    [[ -f "$CUDART_DIR/libcudart.so.12" ]] || die "cudart extract failed"
    ok "cudart ready"
  fi

  if [[ -f "$MODEL_FILE" ]]; then
    skip "GGUF already present ($(du -h "$MODEL_FILE" | awk '{print $1}'))"
  else
    [[ -n "$HF_CLI" ]] || die "hf CLI required to download Hermes GGUF"
    log "downloading $MODEL_REPO / $MODEL_NAME (~4.9 GB)"
    "$HF_CLI" download "$MODEL_REPO" "$MODEL_NAME" --local-dir "$MODEL_DIR"
    [[ -f "$MODEL_FILE" ]] || die "model download did not produce $MODEL_FILE"
    ok "model ready"
  fi
}

# ---- Isaac Lab 3 ----
setup_isaaclab() {
  log "Isaac Lab 3 ($ISAAC_TAG)"
  local root="${Q1_ISAACLAB3_ROOT:-$ISAAC_DEFAULT}"
  # Prefer an existing valid checkout if env already points somewhere else.
  if [[ -n "${Q1_ISAACLAB3_ROOT:-}" && -d "$Q1_ISAACLAB3_ROOT" ]] && is_isaaclab3 "$Q1_ISAACLAB3_ROOT"; then
    root="$Q1_ISAACLAB3_ROOT"
  elif [[ -d "$ISAAC_DEFAULT" ]] && is_isaaclab3 "$ISAAC_DEFAULT"; then
    root="$ISAAC_DEFAULT"
  fi

  if [[ "$CHECK_ONLY" -eq 1 ]]; then
    if [[ -d "$root" ]] && is_isaaclab3 "$root"; then
      ok "Isaac Lab 3 at $root"
      ISAAC_RESOLVED="$root"
      if [[ -d "$root/.venv" || -f "$root/uv.lock" ]]; then ok "uv project present"; else need "uv sync in $root"; MISSING=1; fi
      if [[ -x "$ROOT/scripts/repair_isaaclab_cuda.sh" ]]; then
        if bash "$ROOT/scripts/repair_isaaclab_cuda.sh" --check "$root" >/dev/null 2>&1; then
          ok "torch matches NVIDIA driver"
        else
          need "torch/CUDA mismatch — run: bash scripts/repair_isaaclab_cuda.sh"
          MISSING=1
        fi
      fi
    else
      need "clone $ISAAC_REPO @$ISAAC_TAG → $ISAAC_DEFAULT (do not reuse ~/IsaacLab 2.x)"
      MISSING=1
    fi
    return
  fi

  if [[ -d "$root" ]] && is_isaaclab3 "$root"; then
    skip "Isaac Lab 3 already at $root"
  elif [[ -d "$root" ]] && ! is_isaaclab3 "$root"; then
    die "$root exists but does not look like Isaac Lab 3 (launch_simulation / $ISAAC_TAG). Set Q1_ISAACLAB3_ROOT to a fresh path (default $HOME/IsaacLab3)."
  else
    [[ -n "$UV_BIN" ]] || die "uv is required to clone/sync Isaac Lab 3"
    log "cloning $ISAAC_REPO ($ISAAC_TAG) → $ISAAC_DEFAULT"
    git clone --branch "$ISAAC_TAG" --depth 1 "$ISAAC_REPO" "$ISAAC_DEFAULT"
    root="$ISAAC_DEFAULT"
    is_isaaclab3 "$root" || die "clone finished but $root still not detected as Lab 3"
    ok "cloned $root"
  fi

  if [[ -z "$UV_BIN" ]]; then
    need "uv not on PATH — skip uv sync"
    MISSING=1
  else
    local stamp="$root/.q1_store_uv_sync_stamp"
    # URDF→USD needs the standalone importer (isaacsim-asset-isolated), not full Isaac Sim.
    local want_extra="importers"
    [[ "$WITH_ISAACSIM" -eq 1 ]] && want_extra="importers,isaacsim"
    local prev=""
    [[ -f "$stamp" ]] && prev="$(cat "$stamp" 2>/dev/null || true)"
    if [[ -d "$root/.venv" && -f "$stamp" && "$prev" == "extra=$want_extra" ]]; then
      skip "uv sync already done ($prev)"
    else
      log "uv sync --extra ${want_extra//,/ --extra } — may take a while"
      # shellcheck disable=SC2086
      (cd "$root" && uv sync $(printf -- '--extra %s ' ${want_extra//,/ }))
      printf 'extra=%s\n' "$want_extra" >"$stamp"
      ok "uv sync complete"
    fi
    # Lab 3.0 ships torch+cu130; pin down to the driver-advertised CUDA (e.g. 12.8 → cu128).
    if [[ -x "$ROOT/scripts/repair_isaaclab_cuda.sh" ]]; then
      log "aligning Isaac Lab torch with NVIDIA driver"
      bash "$ROOT/scripts/repair_isaaclab_cuda.sh" "$root" || die "torch/CUDA repair failed"
    fi
  fi

  ISAAC_RESOLVED="$root"
}

ISAAC_RESOLVED=""

if [[ "$ISAAC_ONLY" -eq 0 ]]; then
  setup_hermes
fi
if [[ "$HERMES_ONLY" -eq 0 ]]; then
  setup_isaaclab
fi

if [[ "$CHECK_ONLY" -eq 0 ]]; then
  write_env "${ISAAC_RESOLVED:-${Q1_ISAACLAB3_ROOT:-}}" "$MODEL_FILE"
fi

log "summary"
if [[ "$HERMES_ONLY" -eq 0 ]]; then
  if [[ -n "${ISAAC_RESOLVED:-}" ]]; then
    ok "export Q1_ISAACLAB3_ROOT=$ISAAC_RESOLVED"
  elif [[ -n "${Q1_ISAACLAB3_ROOT:-}" ]]; then
    ok "Q1_ISAACLAB3_ROOT=${Q1_ISAACLAB3_ROOT}"
  else
    need "Isaac Lab 3 path unresolved"
    MISSING=1
  fi
fi
if [[ "$ISAAC_ONLY" -eq 0 ]]; then
  if hermes_import_ok && [[ -f "$MODEL_FILE" ]]; then
    ok "Hermes ready — start with: bash scripts/hermes_server.sh"
  else
    need "Hermes incomplete"
    MISSING=1
  fi
fi
ok "env file: $ENV_FILE"
ok "start web: bash scripts/start_store.sh --port 8878 --with-hermes"

if [[ "$MISSING" -ne 0 ]]; then
  echo
  echo "Setup incomplete (see '! need' lines above)." >&2
  exit 1
fi
echo
echo "Setup OK."
