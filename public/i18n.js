let locale = 'zh-Hant';

export function getLocale() {
  return locale;
}

/** Inline bilingual literal: returns `en` when the UI is English, else `zh`. */
export function tr(zh, en) {
  return locale === 'en' && en != null ? en : zh;
}

/** Catalog field lookup: prefers `<key>_en` when the UI is English. */
export function L(obj, key) {
  if (!obj) return undefined;
  if (locale === 'en') {
    const value = obj[key + '_en'];
    if (value !== undefined && value !== null && value !== '') return value;
  }
  return obj[key];
}

export function localeTag() {
  return locale === 'en' ? 'en-US' : 'zh-TW';
}

export function t(key, vars) {
  const table = STRINGS[locale] || STRINGS['zh-Hant'];
  let text = table[key] ?? STRINGS['zh-Hant'][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll('{' + name + '}', String(value));
    }
  }
  return text;
}

function applyNode(node) {
  if (!(node instanceof Element)) return;
  const key = node.getAttribute('data-i18n');
  if (key) {
    if (node.hasAttribute('data-i18n-html')) node.innerHTML = t(key);
    else node.textContent = t(key);
  }
  const placeholder = node.getAttribute('data-i18n-placeholder');
  if (placeholder) node.setAttribute('placeholder', t(placeholder));
  const aria = node.getAttribute('data-i18n-aria');
  if (aria) node.setAttribute('aria-label', t(aria));
  const title = node.getAttribute('data-i18n-title');
  if (title) node.setAttribute('title', t(title));
}

export function applyI18n(root = document) {
  const year = String(new Date().getFullYear());
  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-Hant';
  document.title = t('document_title');
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t('meta_description'));
  root.querySelectorAll('[data-i18n],[data-i18n-placeholder],[data-i18n-aria],[data-i18n-title]').forEach(applyNode);
  const copyright = document.getElementById('footer-copyright');
  if (copyright) copyright.textContent = t('footer_copyright', { year });
  document.querySelectorAll('[data-lang]').forEach((button) => {
    const active = button.getAttribute('data-lang') === locale;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

export function setLocale(next, { persist = true } = {}) {
  if (!SUPPORTED.has(next)) next = 'zh-Hant';
  locale = next;
  if (persist) {
    try { localStorage.setItem(STORAGE_KEY, locale); } catch {}
  }
  applyI18n();
  window.dispatchEvent(new CustomEvent('q1:locale', { detail: { locale } }));
  return locale;
}

export function initI18n() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE_KEY); } catch {}
  locale = SUPPORTED.has(saved) ? saved : 'zh-Hant';
  applyI18n();
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.addEventListener('click', () => setLocale(button.getAttribute('data-lang')));
  });
  return locale;
}
